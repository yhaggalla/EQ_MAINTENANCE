"""Generate the real-reference-data modules of the P02 prototype.

  artifacts/prototypes/p02-ui/js/catalog.js  from documents/prompt-pack/reference/mechanisms-approved.json
  artifacts/prototypes/p02-ui/js/params.js   from documents/prompt-pack/reference/major-parameters.json

Everything else in the prototype is synthetic and labelled so. Run: python -I tools/p02/build_catalog.py
"""
import json
import pathlib

NL = chr(10)
root = pathlib.Path(__file__).resolve().parents[2]
ref = root / "documents/prompt-pack/reference"
outdir = root / "artifacts/prototypes/p02-ui/js"

# ---------------------------------------------------------------- catalogue
d = json.loads((ref / "mechanisms-approved.json").read_text(encoding="utf-8"))
mains = [{"code": m["code"], "name": m["name"], "active": m["active"]} for m in d["mainMechanisms"]]
subs = [
    {
        "code": s["code"], "main": s["mainCode"], "name": s["name"] or "",
        "sourceName": s["sourceName"] or "", "description": s["description"] or "",
        "active": s["active"], "reserved": s["reserved"],
    }
    for s in d["subMechanisms"]
]

# Self-check against the Master control invariants.
assert len(mains) == 16 and len(subs) == 43, (len(mains), len(subs))
assert sum(1 for s in subs if s["active"]) == 41
assert {s["code"] for s in subs if s["reserved"]} == {"048", "063"}
assert "10" not in {m["code"] for m in mains}
assert all(isinstance(m["code"], str) for m in mains) and all(isinstance(s["code"], str) for s in subs)
names = {s["code"]: s["name"] for s in subs}
assert names["061"] == "Spreader" and names["062"] == "Headblock"

head = (
    "/* GENERATED by tools/p02/build_catalog.py from documents/prompt-pack/reference/mechanisms-approved.json." + NL
    + "   Real reference data (16 main, 43 sub, 41 active, 048/063 inactive, no main 10). Do not edit by hand. */" + NL
)
(outdir / "catalog.js").write_text(
    head + "window.EQ = window.EQ || {};" + NL + "EQ.catalog = " + json.dumps({"mains": mains, "subs": subs}, ensure_ascii=False, indent=1) + ";" + NL,
    encoding="utf-8",
)
print("wrote catalog.js", len(mains), "main", len(subs), "sub")

# ---------------------------------------------------------------- source parameters
pj = json.loads((ref / "major-parameters.json").read_text(encoding="utf-8"))
params = []
for x in pj["parameters"]:
    if x.get("observations"):
        obs = [{"value": o["value"], "drawing": o["drawingNumber"], "page": o["pdfPage"]} for o in x["observations"]]
    else:
        obs = [{"value": x["value"], "drawing": x["source"]["drawingNumber"], "page": x["source"]["pdfPage"]}]
    params.append({
        "code": x["code"], "label": x["label"], "unit": x.get("unit"), "condition": x.get("condition"),
        "use": x["stage1Use"], "verification": x["verification"], "operator": x.get("operator"),
        "motorCount": x.get("motorCount"), "observations": obs,
    })
# U-02 (docs/DECISIONS.md): J526A0400 reports 270 kW for the trolley motor; major-parameters.json holds only 275.
for q in params:
    if q["code"] == "trolley-motor-power":
        q["observations"].append({"value": 270, "drawing": "J526A0400", "page": 1, "supplementary": True})
assert any(q["code"] == "gantry-speed" and len(q["observations"]) == 2 for q in params)
assert not any("overall" in q["code"] for q in params), "no overall-height parameter exists in the reference data"

# ---------------------------------------------------------------- U1-C68 component parameters
# assets/reference/qc-component-parameters.json: the project-authored supplementary observations file that import-parameters
# reads with major-parameters.json (DATA_CONTRACT s3.8 / s8). New definitions are appended; observations on existing codes
# are appended as supplementary source facts. Groups link parameters to scene areas (containers) and part keys.
cp = json.loads((root / "assets/reference/qc-component-parameters.json").read_text(encoding="utf-8"))
manifest = json.loads((root / "artifacts/models/cict-j526a-sts-scene/1/manifest.json").read_text(encoding="utf-8"))
node_keys = {n["key"] for n in manifest["nodes"]}
sources = cp["sources"]
for code, s in sources.items():
    assert s["kind"] in ("sourceDrawing", "sourceManual"), code
    assert (root / s["file"]).is_file(), "source file missing: " + s["file"]
by_code = {q["code"]: q for q in params}
for d in cp["definitions"]:
    assert d["code"] not in by_code, "duplicate parameter code " + d["code"]
    assert d["dataType"] in ("number", "text") and d["use"] in ("major", "technical"), d["code"]
    q = {"code": d["code"], "label": d["label"], "unit": d.get("unit"), "condition": d.get("condition"), "use": d["use"],
         "verification": None, "operator": None, "motorCount": None, "dataType": d["dataType"], "origin": "componentReference", "observations": []}
    params.append(q); by_code[q["code"]] = q
for o in cp["observations"]:
    q = by_code.get(o["parameterCode"]); assert q, "observation for unknown parameter " + o["parameterCode"]
    assert o["sources"] and all(s["document"] in sources and (s["page"] is None or s["page"] >= 1) for s in o["sources"]), o
    if q.get("dataType") == "number" or q.get("origin") is None:
        assert isinstance(o["value"], (int, float)) or q.get("dataType") == "text" or q["code"] == "rail-type", o
    first = o["sources"][0]
    q["observations"].append({"value": o["value"], "drawing": first["document"], "page": first["page"], "locator": first.get("locator"),
                              "refs": o["sources"], "verification": o["verification"], **({"supplementary": True} if q.get("origin") is None else {})})
    if q.get("verification") is None: q["verification"] = o["verification"]
groups = []
for g in cp["groups"]:
    assert g["parameterCodes"] and all(c in by_code for c in g["parameterCodes"]), g["code"]
    assert all(("container." + a) in node_keys for a in g["areas"]), g["code"]
    assert all(k in node_keys for k in g["nodeKeys"]), g["code"]
    groups.append({k: g[k] for k in ("code", "title", "sortOrder", "parameterCodes", "areas", "nodeKeys")})
assert all(q["observations"] for q in params), "every reference parameter has at least one observation"
assert len([q for q in params if len({str(o["value"]) for o in q["observations"]}) > 1]) >= 3  # gantry speed, trolley motor, service crane

head = (
    "/* GENERATED by tools/p02/build_catalog.py from major-parameters.json (+ the U-02 observation from docs/DECISIONS.md)" + NL
    + "   and assets/reference/qc-component-parameters.json (U1-C68 component parameters, sources and groups)." + NL
    + "   Source observations for the CICT-J526A-STS family; not an approved assignment to any real crane. */" + NL
)
(outdir / "params.js").write_text(
    head + "window.EQ = window.EQ || {};" + NL + "EQ.sourceParams = " + json.dumps(params, ensure_ascii=False, indent=1) + ";" + NL
    + "EQ.paramSources = " + json.dumps(sources, ensure_ascii=False, indent=1) + ";" + NL
    + "EQ.paramGroups = " + json.dumps(groups, ensure_ascii=False, indent=1) + ";" + NL,
    encoding="utf-8",
)
print("wrote params.js", len(params), "parameters,", len(groups), "groups,", len(sources), "sources")
