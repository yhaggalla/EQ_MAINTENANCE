// Generates artifacts/prototypes/p02-ui/js/fac-ref.js from documents/prompt-pack/reference/fac-job-list.json (read-only source).
// Usage: node tools/p02b/build_fac_ref.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..', '..');
const src = path.join(repo, 'documents', 'prompt-pack', 'reference', 'fac-job-list.json');
const out = path.join(repo, 'artifacts', 'prototypes', 'p02-ui', 'js', 'fac-ref.js');
const raw = fs.readFileSync(src);
const json = JSON.parse(raw.toString('utf8'));
const body = '/* GENERATED by tools/p02b/build_fac_ref.mjs from documents/prompt-pack/reference/fac-job-list.json (real reference data: the supplied\n   FAC sheet normalised in P01B). Do not edit by hand. Nothing here is progress; all progress/photos/updates are synthetic (fac.js). */\nwindow.EQ = window.EQ || {};\nwindow.EQ.FAC_REF = ' + JSON.stringify(json) + ';\n';
fs.writeFileSync(out, body);
console.log('wrote', path.relative(repo, out), json.jobs.length + ' jobs', body.length + ' bytes');
